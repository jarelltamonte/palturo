enum SkillCategory {
  artsDesign('arts_design', 'Arts and Design'),
  languageCulture('language_culture', 'Language and Cultural Knowledge'),
  everydayPractical('everyday_skills', 'Everyday Practical Skills'),
  agricultureLivelihood('agriculture_livelihood', 'Agriculture and Livelihood');

  final String id;
  final String label;

  const SkillCategory(this.id, this.label);

  static SkillCategory? fromId(String id) {
    for (final c in SkillCategory.values) {
      if (c.id == id) return c;
    }
    return null;
  }
}

class MatchedUser {
  final String id;
  final String name;
  final PersonRole role;
  final String skillName;
  final SkillCategory category;
  final String schedule;
  final String language;
  final String learningStyle;
  final String bio;
  final String? avatarUrl;
  final String? lastMessage;
  final String? lastMessageTime;
  final bool hasUnread;

  const MatchedUser({
    required this.id,
    required this.name,
    required this.role,
    required this.skillName,
    required this.category,
    required this.schedule,
    required this.language,
    required this.learningStyle,
    this.bio = '',
    this.avatarUrl,
    this.lastMessage,
    this.lastMessageTime,
    this.hasUnread = false,
  });

  ImageProvider? get avatarImage =>
      avatarUrl == null ? null : NetworkImage(avatarUrl!);
}

